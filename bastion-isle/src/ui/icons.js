const CACHE = {};
// Strip the size/class attributes and the invisible bounding path; keep only the drawing.
function clean(svg) {
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '').replace(/\s+/g, ' ').trim();
  return body;
}
export function icon(name, cls = '') {
  const key = name + '|' + cls;
  if (CACHE[key]) return CACHE[key];
  const raw = RAW[name] || RAW['hexagon'];
  const s = `<svg class="ic${cls ? ' ' + cls : ''}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${clean(raw)}</svg>`;
  CACHE[key] = s;
  return s;
}
export const ICON_NAMES = Object.keys(RAW);
export function iconPaths(name) { return clean(RAW[name] || RAW['hexagon']); }
